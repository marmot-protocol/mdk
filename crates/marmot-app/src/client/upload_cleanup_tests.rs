/// Build an upload completion without inventing a confirmed message source.
fn finish() -> EncryptedMediaUploadFinish {
    EncryptedMediaUploadFinish {
        group_id: GroupId::new(vec![0xab; 16]),
        source_epoch: 3,
        media_secret: SecretBytes::new(vec![7; 32]),
        should_send: true,
        caption: None,
        message_tags: Vec::new(),
        control: None,
    }
}

/// A real closed account database makes abandonment fail deterministically.
async fn closed_store_client() -> (tempfile::TempDir, AppClient) {
    let dir = tempfile::tempdir().unwrap();
    AccountHome::open(dir.path())
        .create_account("alice")
        .unwrap();
    let app = MarmotApp::with_relay(dir.path(), "wss://relay.example")
        .with_test_relay_client(Arc::new(crate::tests::ScriptedPushRelayClient::default()));
    let client = app.client("alice").await.unwrap();
    app.account_storage("alice").unwrap().close().unwrap();
    (dir, client)
}

/// HTTP, binding, send and token failures retain their classification and detail
/// even when the actual staging cleanup encounters a closed database.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn outgoing_cleanup_failure_preserves_primary_error() {
    let (_dir, client) = closed_store_client().await;
    for error in [
        AppError::MediaUploadTimedOut,
        AppError::InvalidEncryptedMedia("generated binding failure".into()),
        AppError::TransportClosed,
        AppError::InvalidAppMessagePayload("generated token rejection".into()),
    ] {
        let kind = error.privacy_safe_kind();
        let detail = error.to_string();
        let cleanup = client
            .app
            .account_storage("alice")
            .unwrap()
            .app_storage()
            .abandon_attachment_uploads(&[vec![1; 16]])
            .map_err(AppError::from);
        assert!(matches!(
            cleanup,
            Err(AppError::Storage(cgka_traits::StorageError::Closed(_)))
        ));
        let returned = preserve_encrypted_media_upload_error(error, cleanup);
        assert_eq!(returned.privacy_safe_kind(), kind);
        assert_eq!(returned.to_string(), detail);
    }
}

/// A closed account store refuses to stage a send before any upload, and an
/// upload completion with nothing staged still finishes without it.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn closed_storage_refuses_staging_but_not_a_completed_upload() {
    let (_dir, mut client) = closed_store_client().await;
    let mut finish = finish();
    finish.should_send = false;
    let staging = crate::media::outgoing::SendStaging::open(
        &client.app,
        "alice",
        &finish.group_id,
        finish.source_epoch,
    );
    assert!(matches!(
        staging,
        Err(AppError::Storage(cgka_traits::StorageError::Closed(_)))
    ));
    let (reference, _) = crate::media::tests::attachment_worker_fixture(b"generated bytes");
    let result = MediaUploadResult {
        attachments: vec![crate::media::MediaUploadAttachmentResult {
            reference,
            encrypted_size_bytes: 31,
        }],
        sent: None,
    };
    let completed = client
        .finish_encrypted_media_upload(
            finish,
            result.clone(),
            crate::media::outgoing::OutgoingUploads::new(client.app.clone(), "alice".into()),
        )
        .await
        .unwrap();
    assert_eq!(completed.0, result);
}

/// Rows in `table` of the fixture database.
fn count(connection: &rusqlite::Connection, table: &str) -> i64 {
    connection
        .query_row(&format!("SELECT count(*) FROM {table}"), [], |row| {
            row.get(0)
        })
        .unwrap()
}

/// Files under the account's media store directory.
fn media_files_on_disk(app: &MarmotApp) -> usize {
    fn walk(path: &std::path::Path) -> usize {
        std::fs::read_dir(path)
            .map(|entries| {
                entries
                    .flatten()
                    .map(|entry| {
                        if entry.file_type().unwrap().is_dir() {
                            walk(&entry.path())
                        } else {
                            1
                        }
                    })
                    .sum()
            })
            .unwrap_or(0)
    }
    walk(&app.account_dir("alice").join(media_store::MEDIA_DIRECTORY))
}

/// Open the encrypted fixture database for deterministic optional-retention faults.
fn fault_connection(app: &MarmotApp) -> rusqlite::Connection {
    let path = app.account_storage_path("alice");
    let keys = app.account_home().load_signing_keys("alice").unwrap();
    let key = app
        .sqlcipher_key("alice", &keys, &path, crate::SqlcipherDatabaseKind::Session)
        .unwrap();
    let connection = rusqlite::Connection::open(path).unwrap();
    storage_sqlite::open_hardened_sqlcipher(
        &connection,
        &key,
        storage_sqlite::SqlCipherHardening::cipher_only(),
    )
    .unwrap();
    connection
}

/// Serve genuine encrypted PUTs and reject any unexpected acquisition.
async fn upload_endpoint() -> (
    String,
    Arc<std::sync::atomic::AtomicUsize>,
    tokio::task::JoinHandle<()>,
) {
    use tokio::io::{AsyncReadExt, AsyncWriteExt};
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let url = format!("http://{}", listener.local_addr().unwrap());
    let server_url = url.clone();
    let puts = Arc::new(std::sync::atomic::AtomicUsize::new(0));
    let ledger = puts.clone();
    let task = tokio::spawn(async move {
        loop {
            let (mut socket, _) = listener.accept().await.unwrap();
            let mut request = Vec::new();
            let mut buffer = [0u8; 4096];
            let end = loop {
                let count = socket.read(&mut buffer).await.unwrap();
                assert!(count > 0);
                request.extend_from_slice(&buffer[..count]);
                if let Some(i) = request.windows(4).position(|b| b == b"\r\n\r\n") {
                    break i + 4;
                }
            };
            let headers = String::from_utf8_lossy(&request[..end]);
            assert!(
                headers.starts_with("PUT /upload "),
                "retention must not reacquire"
            );
            let size = headers
                .lines()
                .find_map(|line| {
                    line.split_once(':')
                        .filter(|(key, _)| key.eq_ignore_ascii_case("content-length"))
                        .map(|(_, v)| v.trim().parse::<usize>().unwrap())
                })
                .unwrap();
            while request.len() < end + size {
                let count = socket.read(&mut buffer).await.unwrap();
                assert!(count > 0);
                request.extend_from_slice(&buffer[..count]);
            }
            let hash = hex::encode(sha2::Sha256::digest(&request[end..end + size]));
            ledger.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
            let body=serde_json::json!({"url":format!("{server_url}/{hash}"),"sha256":hash,"size":size,"type":"application/octet-stream","uploaded":1}).to_string();
            socket.write_all(format!("HTTP/1.1 201 Created\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{}",body.len(),body).as_bytes()).await.unwrap();
        }
    });
    (url, puts, task)
}

/// File-backed direct and durable-token sends stage the body in the media
/// store, upload once, bind the exact descriptor and promote the staged file
/// into the slot, which reads back in bounded ranges. No snapshot, ciphertext
/// or SQLCipher copy survives the send.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn file_backed_sends_retain_bounded_bodies_and_publish_once() {
    for token_send in [false, true] {
        let dir = tempfile::tempdir().unwrap();
        AccountHome::open(dir.path())
            .create_account("alice")
            .unwrap();
        let app = MarmotApp::with_relay_and_config(
            dir.path(),
            "wss://relay.example",
            crate::MarmotAppConfig::white_noise().with_allow_loopback_blob_endpoints(true),
        )
        .with_test_relay_client(Arc::new(crate::tests::ScriptedPushRelayClient::default()));
        let mut client = app.client("alice").await.unwrap();
        let group = client
            .create_group("generated file retention", &[])
            .await
            .unwrap();
        let group_hex = hex::encode(group.as_slice());
        drop(client);
        let connection = fault_connection(&app);
        let (url, puts, server) = upload_endpoint().await;
        let source_dir = tempfile::tempdir().unwrap();
        let plain = (0..(200 * 1024 + 3))
            .map(|i| (i % 249) as u8)
            .collect::<Vec<_>>();
        let path = source_dir.path().join("generated.bin");
        std::fs::write(&path, &plain).unwrap();
        let request = crate::MediaFileUploadRequest {
            attachments: vec![crate::MediaFileUploadAttachmentRequest {
                source_path: path.to_string_lossy().into_owned(),
                expected_size: Some(plain.len() as u64),
                file_name: "generated.bin".into(),
                media_type: "application/octet-stream".into(),
                dim: None,
                thumbhash: None,
            }],
            caption: None,
            send: true,
            blossom_server: Some(url.clone()),
            message_tags: Vec::new(),
        };
        let runtime = crate::MarmotAppRuntime::new(app.clone());
        let control = Arc::new(crate::MediaFileTransferControl::default());
        let id = if token_send {
            runtime
                .upload_media_files_with_client_token(
                    "alice",
                    &group,
                    request,
                    control.clone(),
                    "generated-file".into(),
                )
                .await
                .unwrap()
                .1
                .unwrap()
                .message_id_hex
        } else {
            runtime
                .upload_media_files("alice", &group, request, control.clone())
                .await
                .unwrap()
                .sent
                .unwrap()
                .message_ids[0]
                .clone()
        };
        assert!(control.processed_bytes() >= plain.len() as u64);
        let asset = tokio::time::timeout(std::time::Duration::from_secs(10), async {
            loop {
                let source = runtime
                    .timeline_message("alice", &group_hex, &id)
                    .unwrap()
                    .and_then(|row| row.source_message_id_hex);
                if let Some(source) = source {
                    let target = crate::AttachmentLocalTarget {
                        message_id_hex: id.clone(),
                        source_message_id_hex: source,
                        attachment_index: 0,
                    };
                    if let Some(asset) = runtime
                        .attachment_local_assets("alice", &group, vec![target])
                        .await
                        .unwrap()
                        .remove(0)
                    {
                        break asset;
                    }
                }
                tokio::time::sleep(std::time::Duration::from_millis(10)).await;
            }
        })
        .await
        .unwrap();
        assert_eq!(asset.byte_count, plain.len() as u64);
        let mut copied = Vec::new();
        while copied.len() < plain.len() {
            let chunk = runtime
                .read_attachment_asset(
                    "alice",
                    asset.reference.clone(),
                    copied.len() as u64,
                    64 * 1024,
                )
                .await
                .unwrap()
                .unwrap();
            assert!(!chunk.is_empty());
            copied.extend_from_slice(&chunk);
        }
        assert_eq!(copied, plain, "token={token_send}");
        assert_eq!(puts.load(std::sync::atomic::Ordering::SeqCst), 1);
        assert_eq!(
            count(&connection, "outgoing_attachment_upload_bodies"),
            0,
            "nothing is staged in SQLCipher"
        );
        assert_eq!(
            count(&connection, "outgoing_attachment_uploads"),
            0,
            "promotion consumed the upload"
        );
        assert_eq!(
            connection
                .query_row(
                    "SELECT count(*) FROM media_files WHERE state=1",
                    [],
                    |row| row.get::<_, i64>(0)
                )
                .unwrap(),
            1,
            "the staged file became the slot's ready file"
        );
        assert_eq!(media_files_on_disk(&app), 1, "no ciphertext is kept");
        let staging = crate::media::file_transfer::media_staging_directory(&app, "alice");
        assert_eq!(
            std::fs::read_dir(&staging)
                .map(|entries| entries.count())
                .unwrap_or(0),
            0,
            "nothing is written to the old staging directory"
        );
        runtime.shutdown_and_close().await.unwrap();
        server.abort();
        assert!(server.await.unwrap_err().is_cancelled());
    }
}

