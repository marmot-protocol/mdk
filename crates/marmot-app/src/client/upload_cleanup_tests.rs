/// A cancellation seen at completion releases the send's uploads: their rows,
/// then their staged files.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn cancelled_finish_frees_staging() {
    let dir = tempfile::tempdir().unwrap();
    AccountHome::open(dir.path())
        .create_account("alice")
        .unwrap();
    let app = MarmotApp::with_relay(dir.path(), "wss://relay.example")
        .with_test_relay_client(Arc::new(crate::tests::ScriptedPushRelayClient::default()));
    let mut client = app.client("alice").await.unwrap();
    let group = client
        .create_group("cancelled completion", &[])
        .await
        .unwrap();
    let connection = fault_connection(&app);
    let bytes = b"completed upload";
    let (reference, _) = crate::media::tests::attachment_worker_fixture(bytes);
    let result = MediaUploadResult {
        attachments: vec![crate::media::MediaUploadAttachmentResult {
            reference,
            encrypted_size_bytes: bytes.len() as u64 + 16,
        }],
        sent: None,
    };
    for should_send in [false, true] {
        let staging = crate::media::outgoing::SendStaging::open(&app, "alice", &group, 3).unwrap();
        let mut uploads = crate::media::outgoing::OutgoingUploads::new(app.clone(), "alice".into());
        staging
            .stage(uploads.tokens_mut(), bytes.len() as u64, |media, target| {
                crate::media::outgoing::stage_body(
                    media,
                    target,
                    &mut &bytes[..],
                    bytes.len() as u64,
                    &|| false,
                )
            })
            .unwrap();
        staging.bind(uploads.tokens(), &result).unwrap();
        assert_eq!(count(&connection, "outgoing_attachment_uploads"), 1);
        assert_eq!(media_files_on_disk(&app), 1);
        let control = Arc::new(crate::MediaFileTransferControl::default());
        control.cancel();
        let mut completion = finish();
        completion.group_id = group.clone();
        completion.should_send = should_send;
        completion.control = Some(control);
        let error = client
            .finish_encrypted_media_upload(completion, result.clone(), uploads)
            .await
            .unwrap_err();
        assert!(matches!(error, AppError::InvalidEncryptedMedia(_)));
        assert_eq!(count(&connection, "outgoing_attachment_uploads"), 0);
        assert_eq!(count(&connection, "media_files"), 0);
        assert_eq!(media_files_on_disk(&app), 0);
    }
}

/// Real direct and durable-token sends ignore the retained-byte budget and a
/// failed prune. A body the disk cannot hold is refused with the storage-full
/// error before any upload; a full upload table or a failed reservation is
/// refused too, and a failed binding after the upload releases what it
/// staged. A refused send publishes nothing and the earlier send stays
/// readable.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn outgoing_sends_ignore_the_budget_and_refuse_what_they_cannot_stage() {
    for token_send in [false, true] {
        for fault in ["quota", "prune", "disk", "cap", "stage", "bind"] {
            let dir = tempfile::tempdir().unwrap();
            AccountHome::open(dir.path())
                .create_account("alice")
                .unwrap();
            let app = MarmotApp::with_relay_and_config(
                dir.path(),
                "wss://relay.example",
                crate::MarmotAppConfig::white_noise().with_allow_loopback_blob_endpoints(true),
            )
            .with_test_relay_client(Arc::new(crate::tests::ScriptedPushRelayClient::default()));
            let mut client = app.client("alice").await.unwrap();
            let group = client
                .create_group("generated retention pressure", &[])
                .await
                .unwrap();
            let group_hex = hex::encode(group.as_slice());
            let storage = app.account_storage("alice").unwrap().app_storage();
            let connection = fault_connection(&app);
            let (url, puts, server) = upload_endpoint().await;
            let request = || crate::MediaUploadRequest {
                attachments: vec![crate::MediaUploadAttachmentRequest {
                    file_name: "generated.bin".into(),
                    media_type: "application/octet-stream".into(),
                    plaintext: vec![42; 1024],
                    dim: None,
                    thumbhash: None,
                }],
                caption: None,
                send: true,
                blossom_server: Some(url.clone()),
                message_tags: Vec::new(),
            };
            // Retain an actual first send; later refusal must leave it readable.
            let initial = client.upload_media(&group, request()).await.unwrap();
            let initial_id = &initial.sent.unwrap().message_ids[0];
            let initial_source: String = connection
                .query_row(
                    "SELECT source_message_id_hex FROM app_events WHERE message_id_hex=?1",
                    [initial_id],
                    |row| row.get(0),
                )
                .unwrap();
            let mut policy = crate::runtime::attachment_controls::default_policy(&app.config);
            match fault {
                "quota"=>{policy.retained_bytes=1024;policy.transfer_limit=1024;},
                "disk"=>policy.disk_reserve=(i64::MAX as u64)-4*512*1024*1024-1,
                "cap"=>{
                    // Fill the upload table, however many rows the first send left.
                    let mut free = 256 - count(&connection, "outgoing_attachment_uploads") as usize;
                    while free > 0 {
                        let batch = free.min(64);
                        storage.stage_attachment_uploads(&group_hex,0,&vec![b"x".as_slice();batch],crate::unix_now_seconds(),1_000_000).unwrap();
                        free -= batch;
                    }
                },
                "prune"=>{
                    storage.stage_attachment_uploads(&group_hex,0,&[b"orphan"],0,1_000_000).unwrap();
                    connection.execute_batch("CREATE TRIGGER fail_optional BEFORE DELETE ON outgoing_attachment_uploads WHEN OLD.slot_json IS NULL BEGIN SELECT RAISE(ABORT,'generated prune fault'); END;").unwrap();
                },
                "stage"=>connection.execute_batch("CREATE TRIGGER fail_optional BEFORE INSERT ON outgoing_attachment_uploads BEGIN SELECT RAISE(ABORT,'generated staging fault'); END;").unwrap(),
                "bind"=>connection.execute_batch("CREATE TRIGGER fail_optional BEFORE UPDATE OF slot_json ON outgoing_attachment_uploads BEGIN SELECT RAISE(ABORT,'generated binding fault'); END;").unwrap(),
                _=>unreachable!(),
            }
            storage
                .set_attachment_download_policy(&policy, crate::unix_now_seconds())
                .unwrap();
            drop(client);
            let staged_before = media_files_on_disk(&app);
            let file_uploads = || {
                let mut statement = connection
                    .prepare(
                        "SELECT token FROM outgoing_attachment_uploads WHERE file_id IS NOT NULL",
                    )
                    .unwrap();
                statement
                    .query_map([], |row| row.get::<_, Vec<u8>>(0))
                    .unwrap()
                    .collect::<Result<std::collections::HashSet<_>, _>>()
                    .unwrap()
            };
            let uploads_before = file_uploads();
            let runtime = crate::MarmotAppRuntime::new(app.clone());
            let sent = if token_send {
                runtime
                    .upload_media_with_client_token(
                        "alice",
                        &group,
                        request(),
                        format!("generated-{fault}"),
                    )
                    .await
                    .map(|(_, accepted)| accepted.unwrap().message_id_hex)
            } else {
                runtime
                    .upload_media("alice", &group, request())
                    .await
                    .map(|result| result.sent.unwrap().message_ids[0].clone())
            };
            let refused = matches!(fault, "disk" | "cap" | "stage" | "bind");
            match sent {
                Ok(id) => {
                    assert!(!refused, "{fault}, token={token_send}: sent");
                    tokio::time::timeout(std::time::Duration::from_secs(10), async {
                        loop {
                            if runtime
                                .timeline_message("alice", &group_hex, &id)
                                .unwrap()
                                .is_some_and(|row| row.source_message_id_hex.is_some())
                            {
                                break;
                            }
                            tokio::time::sleep(std::time::Duration::from_millis(10)).await;
                        }
                    })
                    .await
                    .unwrap();
                }
                Err(error) => {
                    assert!(refused, "{fault}, token={token_send}: {error}");
                    if fault == "disk" {
                        assert!(
                            matches!(
                                error,
                                AppError::Storage(cgka_traits::StorageError::Capacity(_))
                            ),
                            "token={token_send}: {error}"
                        );
                    }
                    // The refused send's upload and staged file are gone;
                    // the first send's may already have been promoted.
                    assert!(
                        file_uploads().is_subset(&uploads_before),
                        "{fault}, token={token_send}"
                    );
                    tokio::time::timeout(std::time::Duration::from_secs(10), async {
                        while media_files_on_disk(&app) != staged_before {
                            tokio::time::sleep(std::time::Duration::from_millis(10)).await;
                        }
                    })
                    .await
                    .unwrap();
                }
            }
            let target = crate::AttachmentLocalTarget {
                message_id_hex: initial_id.clone(),
                source_message_id_hex: initial_source,
                attachment_index: 0,
            };
            // The worker promotes the first send's staged upload.
            let asset = tokio::time::timeout(std::time::Duration::from_secs(10), async {
                loop {
                    if let Some(asset) = runtime
                        .attachment_local_assets("alice", &group, vec![target.clone()])
                        .await
                        .unwrap()
                        .remove(0)
                    {
                        break asset;
                    }
                    tokio::time::sleep(std::time::Duration::from_millis(10)).await;
                }
            })
            .await
            .unwrap();
            assert_eq!(
                &*runtime
                    .read_attachment_asset("alice", asset.reference, 0, 1024)
                    .await
                    .unwrap()
                    .unwrap(),
                &[42; 1024]
            );
            // A send refused before its upload never dials; a refused binding
            // comes after the upload.
            let uploaded = matches!(fault, "quota" | "prune" | "bind");
            assert_eq!(
                puts.load(std::sync::atomic::Ordering::SeqCst),
                1 + usize::from(uploaded),
                "{fault}, token={token_send}: at most one PUT per send"
            );
            assert_eq!(connection.query_row("SELECT count(*) FROM app_events WHERE direction='sent' AND source_message_id_hex IS NOT NULL",[],|row|row.get::<_,i64>(0)).unwrap(),1+i64::from(!refused),"{fault}, token={token_send}: no duplicate publication");
            runtime.shutdown_and_close().await.unwrap();
            server.abort();
            assert!(
                server.await.unwrap_err().is_cancelled(),
                "fixture server must not hide a request assertion panic"
            );
        }
    }
}

/// Staging reads the source outside any account transaction: one held after
/// its first megabyte leaves the account free for other work.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn staging_does_not_hold_an_account_transaction() {
    use std::io::{Cursor, Read};
    struct HeldSource {
        bytes: Cursor<Vec<u8>>,
        entered: Option<std::sync::mpsc::Sender<()>>,
        release: std::sync::mpsc::Receiver<()>,
    }
    impl Read for HeldSource {
        fn read(&mut self, buffer: &mut [u8]) -> std::io::Result<usize> {
            if self.bytes.position() >= 1024 * 1024
                && let Some(entered) = self.entered.take()
            {
                entered.send(()).unwrap();
                self.release
                    .recv_timeout(std::time::Duration::from_secs(15))
                    .unwrap();
            }
            self.bytes.read(buffer)
        }
    }
    let directory = tempfile::tempdir().unwrap();
    AccountHome::open(directory.path())
        .create_account("alice")
        .unwrap();
    let app = MarmotApp::with_relay(directory.path(), "wss://relay.example")
        .with_test_relay_client(Arc::new(crate::tests::ScriptedPushRelayClient::default()));
    let mut client = app.client("alice").await.unwrap();
    let group = client
        .create_group("generated slow staging", &[])
        .await
        .unwrap();
    let storage = app.account_storage("alice").unwrap();
    let staging = crate::media::outgoing::SendStaging::open(&app, "alice", &group, 3).unwrap();
    let (entered, waiting) = std::sync::mpsc::channel();
    let (release, resume) = std::sync::mpsc::channel();
    let worker = std::thread::spawn(move || {
        let len = 2 * 1024 * 1024;
        let mut reader = HeldSource {
            bytes: Cursor::new(vec![42; len]),
            entered: Some(entered),
            release: resume,
        };
        let mut tokens = Vec::new();
        staging
            .stage(&mut tokens, len as u64, |media, target| {
                crate::media::outgoing::stage_body(media, target, &mut reader, len as u64, &|| {
                    false
                })
            })
            .map(|_| tokens)
    });
    waiting
        .recv_timeout(std::time::Duration::from_secs(15))
        .unwrap();
    let probe_storage = storage.clone();
    let (finished, done) = std::sync::mpsc::channel();
    let probe = std::thread::spawn(move || {
        cgka_traits::StorageProvider::with_transaction(&probe_storage, |storage| {
            storage.app_storage().attachment_download_policy(
                &crate::runtime::attachment_controls::default_policy(
                    &crate::MarmotAppConfig::white_noise(),
                ),
            )
        })
        .unwrap();
        finished.send(()).unwrap();
    });
    let progressed = done.recv_timeout(std::time::Duration::from_secs(2)).is_ok();
    release.send(()).unwrap();
    let tokens = worker.join().unwrap().unwrap();
    probe.join().unwrap();
    assert!(
        progressed,
        "account transaction must finish while source read is held"
    );
    crate::media::outgoing::release_outgoing_uploads(app.clone(), "alice".into(), tokens).await;
}

/// A send dropped while its body is still being staged (a caller timing out
/// its upload) releases the reserved upload and its staged file once the
/// staging task finishes.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn a_send_dropped_during_staging_releases_its_upload() {
    let dir = tempfile::tempdir().unwrap();
    AccountHome::open(dir.path())
        .create_account("alice")
        .unwrap();
    let app = MarmotApp::with_relay_and_config(
        dir.path(),
        "wss://relay.example",
        crate::MarmotAppConfig::white_noise().with_allow_loopback_blob_endpoints(true),
    )
    .with_test_relay_client(Arc::new(crate::tests::ScriptedPushRelayClient::default()));
    let mut client = app.client("alice").await.unwrap();
    let group = client
        .create_group("generated dropped staging", &[])
        .await
        .unwrap();
    let connection = fault_connection(&app);
    let source_dir = tempfile::tempdir().unwrap();
    let path = source_dir.path().join("generated.bin");
    let len = 96 * 1024 * 1024u64;
    std::fs::File::create(&path).unwrap().set_len(len).unwrap();
    let control = Arc::new(crate::MediaFileTransferControl::default());
    let request = crate::MediaFileUploadRequest {
        attachments: vec![crate::MediaFileUploadAttachmentRequest {
            source_path: path.to_string_lossy().into_owned(),
            expected_size: Some(len),
            file_name: "generated.bin".into(),
            media_type: "application/octet-stream".into(),
            dim: None,
            thumbhash: None,
        }],
        caption: None,
        send: false,
        // Never reached: the send is dropped while staging.
        blossom_server: Some("http://127.0.0.1:9".into()),
        message_tags: Vec::new(),
    };
    let (http, _finish) = client
        .prepare_encrypted_media_upload_payload(
            &group,
            crate::media::file_transfer::MediaUploadPayload::Files(request, control.clone()),
        )
        .await
        .unwrap();
    let send = tokio::spawn(http.run());
    tokio::time::timeout(std::time::Duration::from_secs(10), async {
        while control.processed_bytes() == 0 {
            tokio::time::sleep(std::time::Duration::from_millis(1)).await;
        }
    })
    .await
    .unwrap();
    send.abort();
    assert!(send.await.unwrap_err().is_cancelled());
    assert!(
        control.processed_bytes() < len,
        "the send was dropped while its body was staging"
    );
    tokio::time::timeout(std::time::Duration::from_secs(60), async {
        while count(&connection, "outgoing_attachment_uploads") != 0
            || media_files_on_disk(&app) != 0
        {
            tokio::time::sleep(std::time::Duration::from_millis(20)).await;
        }
    })
    .await
    .expect("the dropped send's upload and staged file are released");
    assert_eq!(count(&connection, "media_files"), 0);
}

/// A successful upload whose completion is dropped before any message admits
/// it (a stopped worker discarding its queued completion) releases the upload
/// and its staged file.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn a_completed_upload_dropped_before_admission_is_released() {
    let dir = tempfile::tempdir().unwrap();
    AccountHome::open(dir.path())
        .create_account("alice")
        .unwrap();
    let app = MarmotApp::with_relay_and_config(
        dir.path(),
        "wss://relay.example",
        crate::MarmotAppConfig::white_noise().with_allow_loopback_blob_endpoints(true),
    )
    .with_test_relay_client(Arc::new(crate::tests::ScriptedPushRelayClient::default()));
    let mut client = app.client("alice").await.unwrap();
    let group = client
        .create_group("generated dropped completion", &[])
        .await
        .unwrap();
    let connection = fault_connection(&app);
    let (url, puts, server) = upload_endpoint().await;
    let request = crate::MediaUploadRequest {
        attachments: vec![crate::MediaUploadAttachmentRequest {
            file_name: "generated.bin".into(),
            media_type: "application/octet-stream".into(),
            plaintext: vec![42; 4096],
            dim: None,
            thumbhash: None,
        }],
        caption: None,
        send: true,
        blossom_server: Some(url),
        message_tags: Vec::new(),
    };
    let (http, _finish) = client
        .prepare_encrypted_media_upload(&group, request)
        .await
        .unwrap();
    let (_result, uploads) = http.run().await.unwrap();
    assert_eq!(puts.load(std::sync::atomic::Ordering::SeqCst), 1);
    assert_eq!(count(&connection, "outgoing_attachment_uploads"), 1);
    assert_eq!(media_files_on_disk(&app), 1);
    drop(uploads);
    tokio::time::timeout(std::time::Duration::from_secs(10), async {
        while count(&connection, "outgoing_attachment_uploads") != 0
            || media_files_on_disk(&app) != 0
        {
            tokio::time::sleep(std::time::Duration::from_millis(20)).await;
        }
    })
    .await
    .expect("the unadmitted upload and its staged file are released");
    server.abort();
    let _ = server.await;
}

/// An upload-only completion hands back its uploads still armed: if its
/// descriptors never reach the caller, dropping the handoff releases the
/// upload and its staged file.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn an_undelivered_upload_only_result_is_released() {
    let dir = tempfile::tempdir().unwrap();
    AccountHome::open(dir.path())
        .create_account("alice")
        .unwrap();
    let app = MarmotApp::with_relay(dir.path(), "wss://relay.example")
        .with_test_relay_client(Arc::new(crate::tests::ScriptedPushRelayClient::default()));
    let mut client = app.client("alice").await.unwrap();
    let group = client
        .create_group("undelivered upload", &[])
        .await
        .unwrap();
    let connection = fault_connection(&app);
    let bytes = b"completed upload";
    let (reference, _) = crate::media::tests::attachment_worker_fixture(bytes);
    let result = MediaUploadResult {
        attachments: vec![crate::media::MediaUploadAttachmentResult {
            reference,
            encrypted_size_bytes: bytes.len() as u64 + 16,
        }],
        sent: None,
    };
    let staging = crate::media::outgoing::SendStaging::open(&app, "alice", &group, 3).unwrap();
    let mut uploads = crate::media::outgoing::OutgoingUploads::new(app.clone(), "alice".into());
    staging
        .stage(uploads.tokens_mut(), bytes.len() as u64, |media, target| {
            crate::media::outgoing::stage_body(
                media,
                target,
                &mut &bytes[..],
                bytes.len() as u64,
                &|| false,
            )
        })
        .unwrap();
    staging.bind(uploads.tokens(), &result).unwrap();
    let mut completion = finish();
    completion.group_id = group.clone();
    completion.should_send = false;
    let (completed, handoff) = client
        .finish_encrypted_media_upload(completion, result.clone(), uploads)
        .await
        .unwrap();
    assert_eq!(completed, result);
    let handoff = handoff.expect("an upload-only result hands its uploads back armed");
    assert_eq!(count(&connection, "outgoing_attachment_uploads"), 1);
    drop(handoff);
    tokio::time::timeout(std::time::Duration::from_secs(10), async {
        while count(&connection, "outgoing_attachment_uploads") != 0
            || media_files_on_disk(&app) != 0
        {
            tokio::time::sleep(std::time::Duration::from_millis(20)).await;
        }
    })
    .await
    .expect("the undelivered upload and its staged file are released");
}
